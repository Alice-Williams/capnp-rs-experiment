fn emit_enum(
    output: &mut String,
    schema: &CompiledSchema,
    node: &Node,
    enumeration: &capnp_schema::EnumSchema,
    names: &Names,
) -> Result<(), GenerateError> {
    let name = names.get(node.id)?;
    let unrecognized = unique_variant(
        enumeration
            .enumerants
            .iter()
            .map(|value| value.name.as_str()),
    );
    writeln!(output).map_err(|_| GenerateError::Format)?;
    emit_docs(output, schema, node, "Generated enum")?;
    writeln!(output, "#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "pub enum {name} {{").map_err(|_| GenerateError::Format)?;
    for value in &enumeration.enumerants {
        writeln!(output, "    {},", rust_pascal(&value.name)).map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "    {unrecognized}(u16),").map_err(|_| GenerateError::Format)?;
    writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "impl {name} {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub const TYPE_ID: u64 = 0x{:016x};", node.id)
        .map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    pub const fn from_ordinal(value: u16) -> Self {{"
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        match value {{").map_err(|_| GenerateError::Format)?;
    for (ordinal, value) in enumeration.enumerants.iter().enumerate() {
        writeln!(
            output,
            "            {ordinal} => Self::{},",
            rust_pascal(&value.name)
        )
        .map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "            value => Self::{unrecognized}(value),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub const fn ordinal(self) -> u16 {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        match self {{").map_err(|_| GenerateError::Format)?;
    for (ordinal, value) in enumeration.enumerants.iter().enumerate() {
        writeln!(
            output,
            "            Self::{} => {ordinal},",
            rust_pascal(&value.name)
        )
        .map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "            Self::{unrecognized}(value) => value,")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "impl ListElement for {name} {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    fn from_dynamic(value: capnp_schema::DynamicValue) -> Result<Self, capnp_schema::DynamicError> {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        match value {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "            capnp_schema::DynamicValue::Enum(value) if value.type_id == Self::TYPE_ID => Ok(Self::from_ordinal(value.ordinal)),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "            _ => Err(capnp_schema::DynamicError::TypeMismatch {{ expected: \"matching enum list element\" }}),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
    Ok(())
}

fn emit_struct(
    output: &mut String,
    schema: &CompiledSchema,
    node: &Node,
    structure: &capnp_schema::StructSchema,
    names: &Names,
) -> Result<(), GenerateError> {
    let module = names.get(node.id)?;
    let unrecognized = unique_variant(structure.fields.iter().map(|field| field.name.as_str()));
    writeln!(output).map_err(|_| GenerateError::Format)?;
    emit_docs(output, schema, node, "Generated struct module")?;
    writeln!(output, "pub mod {module} {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    use super::*;").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub const TYPE_ID: u64 = 0x{:016x};", node.id)
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    #[derive(Clone, Debug)]").map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    pub struct Reader {{ inner: capnp_schema::DynamicStruct }}"
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    impl capnp_schema::FromDynamicStruct for Reader {{"
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        const TYPE_ID: u64 = TYPE_ID;").map_err(|_| GenerateError::Format)?;
    writeln!(output, "        fn from_dynamic(value: capnp_schema::DynamicStruct) -> Result<Self, capnp_schema::DynamicError> {{ Ok(Self {{ inner: value }}) }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    impl Reader {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "        pub fn from_root(schema: Arc<capnp_schema::CompiledSchema>, message: Arc<capnp_message::OwnedMessage>) -> Result<Self, capnp_schema::DynamicError> {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "            Ok(Self::from_dynamic_struct(capnp_schema::DynamicStruct::root(schema, message, TYPE_ID)?))")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "        pub(super) fn from_dynamic_struct(value: capnp_schema::DynamicStruct) -> Self {{ Self {{ inner: value }} }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "        pub fn dynamic(&self) -> &capnp_schema::DynamicStruct {{ &self.inner }}"
    )
    .map_err(|_| GenerateError::Format)?;

    for (index, field) in structure.fields.iter().enumerate() {
        emit_field_docs(output, schema, node.id, index, field)?;
        emit_reader_field(output, field, names)?;
    }
    if structure.discriminant_count > 0 {
        writeln!(
            output,
            "        pub fn which(&self) -> Result<Which, capnp_schema::DynamicError> {{"
        )
        .map_err(|_| GenerateError::Format)?;
        writeln!(
            output,
            "            match self.inner.union_discriminant()?.unwrap_or(u16::MAX) {{"
        )
        .map_err(|_| GenerateError::Format)?;
        for field in &structure.fields {
            if let Some(discriminant) = field.discriminant_value {
                writeln!(
                    output,
                    "                {discriminant} => Ok(Which::{}),",
                    rust_pascal(&field.name)
                )
                .map_err(|_| GenerateError::Format)?;
            }
        }
        writeln!(
            output,
            "                value => Ok(Which::{unrecognized}(value)),"
        )
        .map_err(|_| GenerateError::Format)?;
        writeln!(output, "            }}").map_err(|_| GenerateError::Format)?;
        writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    impl ListElement for Reader {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "        fn from_dynamic(value: capnp_schema::DynamicValue) -> Result<Self, capnp_schema::DynamicError> {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "            match value {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "                capnp_schema::DynamicValue::Struct(Some(value)) if value.type_id() == TYPE_ID => Ok(Self::from_dynamic_struct(value)),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "                _ => Err(capnp_schema::DynamicError::TypeMismatch {{ expected: \"matching struct list element\" }}),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "            }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;

    writeln!(output, "    #[allow(dead_code)]").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub struct Builder<'schema, 'arena> {{ inner: capnp_schema::DynamicStructBuilder<'schema, 'arena> }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    #[allow(dead_code)]").map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    impl<'schema, 'arena> Builder<'schema, 'arena> {{"
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        pub fn init_root(schema: &'schema capnp_schema::CompiledSchema, arena: &'arena mut capnp_message::ExclusiveArena) -> Result<Self, capnp_schema::DynamicError> {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "            Ok(Self {{ inner: capnp_schema::DynamicStructBuilder::root(schema, arena, TYPE_ID)? }})")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "        pub(super) fn from_dynamic(inner: capnp_schema::DynamicStructBuilder<'schema, 'arena>) -> Self {{ Self {{ inner }} }}")
        .map_err(|_| GenerateError::Format)?;
    for field in &structure.fields {
        emit_builder_field(output, field, names)?;
    }
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;

    if structure.discriminant_count > 0 {
        writeln!(
            output,
            "    #[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]"
        )
        .map_err(|_| GenerateError::Format)?;
        writeln!(output, "    pub enum Which {{").map_err(|_| GenerateError::Format)?;
        for field in &structure.fields {
            if field.discriminant_value.is_some() {
                writeln!(output, "        {},", rust_pascal(&field.name))
                    .map_err(|_| GenerateError::Format)?;
            }
        }
        writeln!(output, "        {unrecognized}(u16),").map_err(|_| GenerateError::Format)?;
        writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
    Ok(())
}

fn emit_reader_field(
    output: &mut String,
    field: &Field,
    names: &Names,
) -> Result<(), GenerateError> {
    let method = rust_snake(&field.name);
    match &field.kind {
        FieldKind::Group { type_id } => {
            let target = names.get(*type_id)?;
            writeln!(output, "        pub fn {method}(&self) -> Result<super::{target}::Reader, capnp_schema::DynamicError> {{")
                .map_err(|_| GenerateError::Format)?;
            writeln!(
                output,
                "            match self.inner.get({:?})? {{",
                field.name
            )
            .map_err(|_| GenerateError::Format)?;
            writeln!(output, "                capnp_schema::DynamicValue::Struct(Some(value)) => Ok(super::{target}::Reader::from_dynamic_struct(value)),")
                .map_err(|_| GenerateError::Format)?;
            emit_mismatch(output, "group field", 16)?;
            writeln!(output, "            }}\n        }}").map_err(|_| GenerateError::Format)?;
        }
        FieldKind::Slot { ty, .. } => emit_typed_getter(output, &method, &field.name, ty, names)?,
    }
    Ok(())
}

fn emit_typed_getter(
    output: &mut String,
    method: &str,
    wire_name: &str,
    ty: &Type,
    names: &Names,
) -> Result<(), GenerateError> {
    let (rust_type, pattern, value) = reader_shape(ty, names)?;
    writeln!(
        output,
        "        pub fn {method}(&self) -> Result<{rust_type}, capnp_schema::DynamicError> {{"
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "            match self.inner.get({wire_name:?})? {{"
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(output, "                {pattern} => Ok({value}),")
        .map_err(|_| GenerateError::Format)?;
    emit_mismatch(output, "field value matching generated type", 16)?;
    writeln!(output, "            }}\n        }}").map_err(|_| GenerateError::Format)?;
    Ok(())
}

fn reader_shape(ty: &Type, names: &Names) -> Result<(String, String, String), GenerateError> {
    let scalar = |rust_type: &str, variant: &str| {
        (
            rust_type.to_owned(),
            format!("capnp_schema::DynamicValue::{variant}(value)"),
            "value".to_owned(),
        )
    };
    Ok(match ty {
        Type::Void => (
            "()".into(),
            "capnp_schema::DynamicValue::Void".into(),
            "()".into(),
        ),
        Type::Bool => scalar("bool", "Bool"),
        Type::Int8 => scalar("i8", "Int8"),
        Type::Int16 => scalar("i16", "Int16"),
        Type::Int32 => scalar("i32", "Int32"),
        Type::Int64 => scalar("i64", "Int64"),
        Type::UInt8 => scalar("u8", "UInt8"),
        Type::UInt16 => scalar("u16", "UInt16"),
        Type::UInt32 => scalar("u32", "UInt32"),
        Type::UInt64 => scalar("u64", "UInt64"),
        Type::Float32 => scalar("f32", "Float32"),
        Type::Float64 => scalar("f64", "Float64"),
        Type::Text => scalar("String", "Text"),
        Type::Data => scalar("Vec<u8>", "Data"),
        Type::List(element) => (
            format!("Option<ListReader<{}>>", list_type(element, names)?),
            "capnp_schema::DynamicValue::List(value)".into(),
            "value.map(ListReader::from_dynamic)".into(),
        ),
        Type::Enum { type_id, .. } => {
            let name = names.get(*type_id)?;
            (
                format!("super::{name}"),
                "capnp_schema::DynamicValue::Enum(value)".into(),
                format!("super::{name}::from_ordinal(value.ordinal)"),
            )
        }
        Type::Struct { type_id, .. } => {
            let name = names.get(*type_id)?;
            (
                format!("Option<super::{name}::Reader>"),
                "capnp_schema::DynamicValue::Struct(value)".into(),
                format!("value.map(super::{name}::Reader::from_dynamic_struct)"),
            )
        }
        Type::Interface { .. } => scalar("Option<u32>", "Capability"),
        Type::AnyPointer(_) => scalar("capnp_schema::DynamicAnyPointer", "AnyPointer"),
    })
}

fn list_type(ty: &Type, names: &Names) -> Result<String, GenerateError> {
    Ok(match ty {
        Type::Void => "()".into(),
        Type::Bool => "bool".into(),
        Type::Int8 => "i8".into(),
        Type::Int16 => "i16".into(),
        Type::Int32 => "i32".into(),
        Type::Int64 => "i64".into(),
        Type::UInt8 => "u8".into(),
        Type::UInt16 => "u16".into(),
        Type::UInt32 => "u32".into(),
        Type::UInt64 => "u64".into(),
        Type::Float32 => "f32".into(),
        Type::Float64 => "f64".into(),
        Type::Text => "String".into(),
        Type::Data => "Vec<u8>".into(),
        Type::List(element) => format!("ListReader<{}>", list_type(element, names)?),
        Type::Enum { type_id, .. } => format!("super::{}", names.get(*type_id)?),
        Type::Struct { type_id, .. } => format!("super::{}::Reader", names.get(*type_id)?),
        Type::Interface { .. } => "Option<u32>".into(),
        Type::AnyPointer(_) => "capnp_schema::DynamicAnyPointer".into(),
    })
}

fn emit_builder_field(
    output: &mut String,
    field: &Field,
    names: &Names,
) -> Result<(), GenerateError> {
    let method = rust_snake(&field.name);
    match &field.kind {
        FieldKind::Group { type_id } => {
            let target = names.get(*type_id)?;
            writeln!(output, "        pub fn {method}(&mut self) -> Result<super::{target}::Builder<'schema, '_>, capnp_schema::DynamicError> {{")
                .map_err(|_| GenerateError::Format)?;
            writeln!(
                output,
                "            Ok(super::{target}::Builder::from_dynamic(self.inner.group({:?})?))",
                field.name
            )
            .map_err(|_| GenerateError::Format)?;
            writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
        }
        FieldKind::Slot { ty, .. } => match ty {
            Type::Struct { type_id, .. } => {
                let target = names.get(*type_id)?;
                writeln!(output, "        pub fn init_{method}(&mut self) -> Result<super::{target}::Builder<'schema, '_>, capnp_schema::DynamicError> {{")
                    .map_err(|_| GenerateError::Format)?;
                writeln!(output, "            Ok(super::{target}::Builder::from_dynamic(self.inner.init_struct({:?})?))", field.name)
                    .map_err(|_| GenerateError::Format)?;
                writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
            }
            Type::List(_) => {
                writeln!(output, "        pub fn init_{method}(&mut self, element_count: u32) -> Result<capnp_schema::DynamicListBuilder<'schema, '_>, capnp_schema::DynamicError> {{")
                    .map_err(|_| GenerateError::Format)?;
                writeln!(
                    output,
                    "            self.inner.init_list({:?}, element_count)",
                    field.name
                )
                .map_err(|_| GenerateError::Format)?;
                writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
            }
            _ => {
                let Some((arg_type, input)) = builder_shape(ty, names)? else {
                    return Ok(());
                };
                let argument = if matches!(ty, Type::Void) {
                    "_value"
                } else {
                    "value"
                };
                writeln!(output, "        pub fn set_{method}(&mut self, {argument}: {arg_type}) -> Result<(), capnp_schema::DynamicError> {{")
                    .map_err(|_| GenerateError::Format)?;
                writeln!(
                    output,
                    "            self.inner.set({:?}, {input})",
                    field.name
                )
                .map_err(|_| GenerateError::Format)?;
                writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
            }
        },
    }
    Ok(())
}

fn builder_shape(ty: &Type, names: &Names) -> Result<Option<(String, String)>, GenerateError> {
    let scalar = |rust_type: &str, variant: &str| {
        Some((
            rust_type.to_owned(),
            format!("capnp_schema::DynamicInput::{variant}(value)"),
        ))
    };
    Ok(match ty {
        Type::Void => Some(("()".into(), "capnp_schema::DynamicInput::Void".into())),
        Type::Bool => scalar("bool", "Bool"),
        Type::Int8 => scalar("i8", "Int8"),
        Type::Int16 => scalar("i16", "Int16"),
        Type::Int32 => scalar("i32", "Int32"),
        Type::Int64 => scalar("i64", "Int64"),
        Type::UInt8 => scalar("u8", "UInt8"),
        Type::UInt16 => scalar("u16", "UInt16"),
        Type::UInt32 => scalar("u32", "UInt32"),
        Type::UInt64 => scalar("u64", "UInt64"),
        Type::Float32 => scalar("f32", "Float32"),
        Type::Float64 => scalar("f64", "Float64"),
        Type::Text => scalar("&str", "Text"),
        Type::Data => scalar("&[u8]", "Data"),
        Type::Enum { type_id, .. } => {
            let name = names.get(*type_id)?;
            Some((
                format!("super::{name}"),
                "capnp_schema::DynamicInput::Enum(value.ordinal())".into(),
            ))
        }
        Type::Interface { .. } | Type::AnyPointer(_) => scalar("u32", "Capability"),
        Type::List(_) | Type::Struct { .. } => None,
    })
}

fn emit_mismatch(output: &mut String, expected: &str, spaces: usize) -> Result<(), GenerateError> {
    writeln!(
        output,
        "{padding}_ => Err(capnp_schema::DynamicError::TypeMismatch {{ expected: {expected:?} }}),",
        padding = " ".repeat(spaces)
    )
    .map_err(|_| GenerateError::Format)
}

fn emit_docs(
    output: &mut String,
    schema: &CompiledSchema,
    node: &Node,
    fallback: &str,
) -> Result<(), GenerateError> {
    let docs = schema
        .source_info(node.id)
        .map(|info| info.doc_comment.as_str())
        .filter(|docs| !docs.trim().is_empty());
    if let Some(docs) = docs {
        for line in docs.lines() {
            writeln!(output, "/// {}", line.trim_end()).map_err(|_| GenerateError::Format)?;
        }
    } else {
        writeln!(output, "/// {fallback} for `{}`.", node.display_name)
            .map_err(|_| GenerateError::Format)?;
    }
    Ok(())
}

fn emit_field_docs(
    output: &mut String,
    schema: &CompiledSchema,
    node_id: NodeId,
    index: usize,
    field: &Field,
) -> Result<(), GenerateError> {
    let docs = schema
        .source_info(node_id)
        .and_then(|info| info.members.get(index))
        .map(|member| member.doc_comment.as_str())
        .filter(|docs| !docs.trim().is_empty());
    if let Some(docs) = docs {
        for line in docs.lines() {
            writeln!(output, "        /// {}", line.trim_end())
                .map_err(|_| GenerateError::Format)?;
        }
    } else {
        writeln!(output, "        /// Reads `{}`.", field.name)
            .map_err(|_| GenerateError::Format)?;
    }
    Ok(())
}

fn module_name_from_filename(filename: &str) -> Result<String, GenerateError> {
    let basename = filename
        .rsplit(['/', '\\'])
        .next()
        .unwrap_or(filename)
        .strip_suffix(".capnp")
        .unwrap_or(filename);
    let name = rust_snake(basename);
    if name.is_empty() {
        Err(GenerateError::InvalidName(filename.to_owned()))
    } else {
        Ok(name)
    }
}

fn rust_snake(input: &str) -> String {
    let mut output = String::new();
    let mut previous_was_lower_or_digit = false;
    for character in input.chars() {
        if character.is_ascii_alphanumeric() {
            if character.is_ascii_uppercase()
                && previous_was_lower_or_digit
                && !output.ends_with('_')
            {
                output.push('_');
            }
            output.push(character.to_ascii_lowercase());
            previous_was_lower_or_digit =
                character.is_ascii_lowercase() || character.is_ascii_digit();
        } else {
            if !output.is_empty() && !output.ends_with('_') {
                output.push('_');
            }
            previous_was_lower_or_digit = false;
        }
    }
    while output.ends_with('_') {
        output.pop();
    }
    rust_identifier(output)
}

fn rust_pascal(input: &str) -> String {
    let mut output = String::new();
    let mut uppercase = true;
    for character in input.chars() {
        if character.is_ascii_alphanumeric() {
            if uppercase {
                output.push(character.to_ascii_uppercase());
                uppercase = false;
            } else {
                output.push(character);
            }
        } else {
            uppercase = true;
        }
    }
    if output.as_bytes().first().is_some_and(u8::is_ascii_digit) {
        output.insert(0, '_');
    }
    if is_keyword(&output.to_ascii_lowercase()) {
        output.push('_');
    }
    output
}

fn rust_identifier(mut value: String) -> String {
    if value.as_bytes().first().is_some_and(u8::is_ascii_digit) {
        value.insert(0, '_');
    }
    if is_keyword(&value) {
        value.push('_');
    }
    value
}

fn unique_variant<'a>(names: impl Iterator<Item = &'a str>) -> String {
    let used = names.map(rust_pascal).collect::<BTreeSet<_>>();
    let mut candidate = "Unrecognized".to_owned();
    while used.contains(&candidate) {
        candidate.push('_');
    }
    candidate
}


fn emit_enum(
    output: &mut String,
    schema: &CompiledSchema,
    node: &Node,
    enumeration: &capnp_schema::EnumSchema,
    names: &Names,
) -> Result<(), GenerateError> {
    let name = names.get(node.id)?;
    let unrecognized = unique_variant(
        enumeration
            .enumerants
            .iter()
            .map(|value| value.name.as_str()),
    );
    writeln!(output).map_err(|_| GenerateError::Format)?;
    emit_docs(output, schema, node, "Generated enum")?;
    writeln!(output, "#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "pub enum {name} {{").map_err(|_| GenerateError::Format)?;
    for value in &enumeration.enumerants {
        writeln!(output, "    {},", rust_pascal(&value.name)).map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "    {unrecognized}(u16),").map_err(|_| GenerateError::Format)?;
    writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "impl {name} {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub const TYPE_ID: u64 = 0x{:016x};", node.id)
        .map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    pub const fn from_ordinal(value: u16) -> Self {{"
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        match value {{").map_err(|_| GenerateError::Format)?;
    for (ordinal, value) in enumeration.enumerants.iter().enumerate() {
        writeln!(
            output,
            "            {ordinal} => Self::{},",
            rust_pascal(&value.name)
        )
        .map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "            value => Self::{unrecognized}(value),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub const fn ordinal(self) -> u16 {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        match self {{").map_err(|_| GenerateError::Format)?;
    for (ordinal, value) in enumeration.enumerants.iter().enumerate() {
        writeln!(
            output,
            "            Self::{} => {ordinal},",
            rust_pascal(&value.name)
        )
        .map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "            Self::{unrecognized}(value) => value,")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "impl ListElement for {name} {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    fn from_dynamic(value: capnp_schema::DynamicValue) -> Result<Self, capnp_schema::DynamicError> {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        match value {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "            capnp_schema::DynamicValue::Enum(value) if value.type_id == Self::TYPE_ID => Ok(Self::from_ordinal(value.ordinal)),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "            _ => Err(capnp_schema::DynamicError::TypeMismatch {{ expected: \"matching enum list element\" }}),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "impl GeneratedType for {name} {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    fn schema_type() -> capnp_schema::Type {{ capnp_schema::Type::Enum {{ type_id: Self::TYPE_ID, brand: capnp_schema::Brand::default() }} }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "impl FieldInput for {name} {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    fn set_field(self, builder: &mut capnp_schema::DynamicStructBuilder<'_, '_>, field: &str) -> Result<(), capnp_schema::DynamicError> {{ builder.set(field, capnp_schema::DynamicInput::Enum(self.ordinal())) }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
    Ok(())
}

fn emit_constant(
    output: &mut String,
    schema: &CompiledSchema,
    node: &Node,
    constant: &capnp_schema::ConstSchema,
    names: &Names,
) -> Result<(), GenerateError> {
    let name = rust_snake(node.short_name().unwrap_or(&node.display_name));
    let constant_name = name.to_ascii_uppercase();
    writeln!(output).map_err(|_| GenerateError::Format)?;
    emit_docs(output, schema, node, "Generated constant")?;
    if let Some((rust_type, value)) = literal_constant(&constant.ty, &constant.value, names)? {
        writeln!(output, "pub const {constant_name}: {rust_type} = {value};")
            .map_err(|_| GenerateError::Format)?;
        return Ok(());
    }

    match &constant.ty {
        Type::List(element) => {
            let element_type = rust_value_type(schema, element, names, &[])?
                .trim_start_matches("super::")
                .to_owned();
            writeln!(output, "pub fn {name}(schema: Arc<capnp_schema::CompiledSchema>, limits: capnp_message::ReaderLimits) -> Result<Option<ListReader<{element_type}>>, capnp_schema::DynamicError> {{")
                .map_err(|_| GenerateError::Format)?;
            emit_constant_lookup(output, node.id)?;
            writeln!(output, "    let capnp_schema::Type::List(element) = &constant.ty else {{ return Err(capnp_schema::DynamicError::TypeMismatch {{ expected: \"list constant\" }}); }};")
                .map_err(|_| GenerateError::Format)?;
            writeln!(output, "    Ok(capnp_schema::DynamicList::from_value(Arc::clone(&schema), (**element).clone(), &constant.value, limits)?.map(ListReader::from_dynamic))")
                .map_err(|_| GenerateError::Format)?;
            writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
        }
        Type::Struct { type_id, brand } => {
            let target = struct_reader_type(schema, *type_id, Some(brand), names, &[])?
                .trim_start_matches("super::")
                .to_owned();
            writeln!(output, "pub fn {name}(schema: Arc<capnp_schema::CompiledSchema>, limits: capnp_message::ReaderLimits) -> Result<Option<{target}>, capnp_schema::DynamicError> {{")
                .map_err(|_| GenerateError::Format)?;
            emit_constant_lookup(output, node.id)?;
            writeln!(output, "    let capnp_schema::Type::Struct {{ type_id, brand }} = &constant.ty else {{ return Err(capnp_schema::DynamicError::TypeMismatch {{ expected: \"struct constant\" }}); }};")
                .map_err(|_| GenerateError::Format)?;
            writeln!(output, "    Ok(capnp_schema::DynamicStruct::from_branded_value(Arc::clone(&schema), *type_id, brand.clone(), &constant.value, limits)?.map(<{target}>::from_dynamic_struct))")
                .map_err(|_| GenerateError::Format)?;
            writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
        }
        _ => {}
    }
    Ok(())
}

fn emit_constant_lookup(output: &mut String, id: NodeId) -> Result<(), GenerateError> {
    writeln!(output, "    let node = schema.node(0x{id:016x}).ok_or(capnp_schema::DynamicError::UnknownSchema(0x{id:016x}))?;")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    let capnp_schema::NodeKind::Const(constant) = &node.kind else {{ return Err(capnp_schema::DynamicError::TypeMismatch {{ expected: \"constant schema node\" }}); }};")
        .map_err(|_| GenerateError::Format)
}

fn literal_constant(
    ty: &Type,
    value: &capnp_schema::Value,
    names: &Names,
) -> Result<Option<(String, String)>, GenerateError> {
    use capnp_schema::Value;
    Ok(match (ty, value) {
        (Type::Void, Value::Void) => Some(("()".into(), "()".into())),
        (Type::Bool, Value::Bool(value)) => Some(("bool".into(), value.to_string())),
        (Type::Int8, Value::Int8(value)) => Some(("i8".into(), value.to_string())),
        (Type::Int16, Value::Int16(value)) => Some(("i16".into(), value.to_string())),
        (Type::Int32, Value::Int32(value)) => Some(("i32".into(), value.to_string())),
        (Type::Int64, Value::Int64(value)) => Some(("i64".into(), value.to_string())),
        (Type::UInt8, Value::UInt8(value)) => Some(("u8".into(), value.to_string())),
        (Type::UInt16, Value::UInt16(value)) => Some(("u16".into(), value.to_string())),
        (Type::UInt32, Value::UInt32(value)) => Some(("u32".into(), value.to_string())),
        (Type::UInt64, Value::UInt64(value)) => Some(("u64".into(), value.to_string())),
        (Type::Float32, Value::Float32(value)) => Some((
            "f32".into(),
            format!("f32::from_bits(0x{:08x})", value.to_bits()),
        )),
        (Type::Float64, Value::Float64(value)) => Some((
            "f64".into(),
            format!("f64::from_bits(0x{:016x})", value.to_bits()),
        )),
        (Type::Text, Value::Text(value)) => Some(("&str".into(), format!("{value:?}"))),
        (Type::Data, Value::Data(value)) => Some(("&[u8]".into(), format!("&{value:?}"))),
        (Type::Enum { type_id, .. }, Value::Enum(value)) => Some((
            names.reference(*type_id, false)?,
            format!(
                "{}::from_ordinal({value})",
                names.reference(*type_id, false)?
            ),
        )),
        _ => None,
    })
}

fn emit_annotation(
    output: &mut String,
    schema: &CompiledSchema,
    node: &Node,
    annotation: &capnp_schema::AnnotationSchema,
    _names: &Names,
) -> Result<(), GenerateError> {
    let module = format!(
        "{}_annotation",
        rust_snake(node.short_name().unwrap_or(&node.display_name))
    );
    let (rust_type, value_pattern, value_expression) = annotation_value_shape(&annotation.ty);
    let targets = annotation.targets;
    writeln!(output).map_err(|_| GenerateError::Format)?;
    emit_docs(output, schema, node, "Generated annotation")?;
    writeln!(output, "pub mod {module} {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub const TYPE_ID: u64 = 0x{:016x};", node.id)
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub type Value = {rust_type};").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub const TARGETS: capnp_schema::AnnotationTargets = capnp_schema::AnnotationTargets {{")
        .map_err(|_| GenerateError::Format)?;
    for (name, value) in [
        ("file", targets.file),
        ("constant", targets.constant),
        ("enumeration", targets.enumeration),
        ("enumerant", targets.enumerant),
        ("structure", targets.structure),
        ("field", targets.field),
        ("union", targets.union),
        ("group", targets.group),
        ("interface", targets.interface),
        ("method", targets.method),
        ("parameter", targets.parameter),
        ("annotation", targets.annotation),
    ] {
        writeln!(output, "        {name}: {value},").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "    }};").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub fn find(values: &[capnp_schema::Annotation]) -> Option<&capnp_schema::Annotation> {{ values.iter().find(|value| value.id == TYPE_ID) }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub fn decode(annotation: &capnp_schema::Annotation) -> Result<Value, capnp_schema::DynamicError> {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        if annotation.id != TYPE_ID {{ return Err(capnp_schema::DynamicError::TypeMismatch {{ expected: \"matching annotation ID\" }}); }}")
        .map_err(|_| GenerateError::Format)?;
    if value_pattern == "value" {
        writeln!(output, "        Ok(annotation.value.clone())")
            .map_err(|_| GenerateError::Format)?;
    } else {
        writeln!(output, "        match &annotation.value {{")
            .map_err(|_| GenerateError::Format)?;
        writeln!(
            output,
            "            {value_pattern} => Ok({value_expression}),"
        )
        .map_err(|_| GenerateError::Format)?;
        writeln!(output, "            _ => Err(capnp_schema::DynamicError::TypeMismatch {{ expected: \"matching annotation value\" }}),")
            .map_err(|_| GenerateError::Format)?;
        writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "    }}\n}}").map_err(|_| GenerateError::Format)?;
    Ok(())
}

fn annotation_value_shape(ty: &Type) -> (&'static str, &'static str, &'static str) {
    match ty {
        Type::Void => ("()", "capnp_schema::Value::Void", "()"),
        Type::Bool => ("bool", "capnp_schema::Value::Bool(value)", "*value"),
        Type::Int8 => ("i8", "capnp_schema::Value::Int8(value)", "*value"),
        Type::Int16 => ("i16", "capnp_schema::Value::Int16(value)", "*value"),
        Type::Int32 => ("i32", "capnp_schema::Value::Int32(value)", "*value"),
        Type::Int64 => ("i64", "capnp_schema::Value::Int64(value)", "*value"),
        Type::UInt8 => ("u8", "capnp_schema::Value::UInt8(value)", "*value"),
        Type::UInt16 => ("u16", "capnp_schema::Value::UInt16(value)", "*value"),
        Type::UInt32 => ("u32", "capnp_schema::Value::UInt32(value)", "*value"),
        Type::UInt64 => ("u64", "capnp_schema::Value::UInt64(value)", "*value"),
        Type::Float32 => ("f32", "capnp_schema::Value::Float32(value)", "*value"),
        Type::Float64 => ("f64", "capnp_schema::Value::Float64(value)", "*value"),
        Type::Text => (
            "String",
            "capnp_schema::Value::Text(value)",
            "value.clone()",
        ),
        Type::Data => (
            "Vec<u8>",
            "capnp_schema::Value::Data(value)",
            "value.clone()",
        ),
        Type::Enum { .. } => ("u16", "capnp_schema::Value::Enum(value)", "*value"),
        _ => ("capnp_schema::Value", "value", "value.clone()"),
    }
}

#[derive(Clone, Debug)]
struct GenericParameter {
    scope_id: NodeId,
    index: u16,
    name: String,
}

const IMPLICIT_METHOD_SCOPE: NodeId = NodeId::MAX;

fn generic_parameters(schema: &CompiledSchema, node: &Node) -> Vec<GenericParameter> {
    let mut scopes = Vec::new();
    let mut current = Some(node);
    while let Some(value) = current {
        scopes.push(value);
        current = (value.scope_id != 0)
            .then(|| schema.node(value.scope_id))
            .flatten();
    }
    scopes.reverse();
    let mut used = BTreeSet::new();
    let mut output = Vec::new();
    for scope in scopes {
        for (index, parameter) in scope.parameters.iter().enumerate() {
            let base = rust_pascal(&parameter.name);
            let mut name = base.clone();
            let mut suffix = 2usize;
            while !used.insert(name.clone()) {
                name = format!("{base}{suffix}");
                suffix += 1;
            }
            if let Ok(index) = u16::try_from(index) {
                output.push(GenericParameter {
                    scope_id: scope.id,
                    index,
                    name,
                });
            }
        }
    }
    let mut referenced = BTreeSet::new();
    if let NodeKind::Struct(structure) = &node.kind {
        for field in &structure.fields {
            if let FieldKind::Slot { ty, .. } = &field.kind {
                collect_parameter_references(ty, &mut referenced);
            }
        }
    }
    for (scope_id, index) in referenced {
        if output
            .iter()
            .any(|parameter| parameter.scope_id == scope_id && parameter.index == index)
        {
            continue;
        }
        let base = schema
            .node(scope_id)
            .and_then(|scope| scope.parameters.get(usize::from(index)))
            .map(|parameter| rust_pascal(&parameter.name))
            .unwrap_or_else(|| format!("P{index}"));
        let mut name = base.clone();
        let mut suffix = 2usize;
        while !used.insert(name.clone()) {
            name = format!("{base}{suffix}");
            suffix += 1;
        }
        output.push(GenericParameter {
            scope_id,
            index,
            name,
        });
    }
    output
}

fn collect_parameter_references(ty: &Type, output: &mut BTreeSet<(NodeId, u16)>) {
    match ty {
        Type::List(element) => collect_parameter_references(element, output),
        Type::Enum { brand, .. } | Type::Struct { brand, .. } | Type::Interface { brand, .. } => {
            for scope in &brand.scopes {
                if let ScopeBinding::Bind(bindings) = &scope.binding {
                    for binding in bindings {
                        if let BrandBinding::Type(ty) = binding {
                            collect_parameter_references(ty, output);
                        }
                    }
                }
            }
        }
        Type::AnyPointer(AnyPointerType::Parameter { scope_id, index }) => {
            output.insert((*scope_id, *index));
        }
        Type::Void
        | Type::Bool
        | Type::Int8
        | Type::Int16
        | Type::Int32
        | Type::Int64
        | Type::UInt8
        | Type::UInt16
        | Type::UInt32
        | Type::UInt64
        | Type::Float32
        | Type::Float64
        | Type::Text
        | Type::Data
        | Type::AnyPointer(_) => {}
    }
}

fn generic_declaration(parameters: &[GenericParameter], defaults: bool) -> String {
    if parameters.is_empty() {
        return String::new();
    }
    let values = parameters
        .iter()
        .map(|parameter| {
            if defaults {
                format!("{} = capnp_schema::DynamicValue", parameter.name)
            } else {
                parameter.name.clone()
            }
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!("<{values}>")
}

fn generic_arguments(parameters: &[GenericParameter]) -> String {
    if parameters.is_empty() {
        String::new()
    } else {
        format!(
            "<{}>",
            parameters
                .iter()
                .map(|parameter| parameter.name.as_str())
                .collect::<Vec<_>>()
                .join(", ")
        )
    }
}

fn marker_type(parameters: &[GenericParameter]) -> String {
    match parameters {
        [] => "()".to_owned(),
        [parameter] => parameter.name.clone(),
        _ => {
            format!(
                "({})",
                parameters
                    .iter()
                    .map(|parameter| parameter.name.as_str())
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        }
    }
}

fn parameter_name(parameters: &[GenericParameter], scope_id: NodeId, index: u16) -> Option<&str> {
    parameters
        .iter()
        .find(|parameter| parameter.scope_id == scope_id && parameter.index == index)
        .map(|parameter| parameter.name.as_str())
}

fn generated_brand_expression(parameters: &[GenericParameter]) -> String {
    if parameters.is_empty() {
        return "capnp_schema::Brand::default()".to_owned();
    }
    let mut scopes: BTreeMap<NodeId, Vec<&GenericParameter>> = BTreeMap::new();
    for parameter in parameters {
        scopes
            .entry(parameter.scope_id)
            .or_default()
            .push(parameter);
    }
    let scopes = scopes
        .into_iter()
        .map(|(scope_id, values)| {
            let bindings = values
                .into_iter()
                .map(|parameter| {
                    format!(
                        "capnp_schema::BrandBinding::Type({}::schema_type())",
                        parameter.name
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!("capnp_schema::BrandScope {{ scope_id: 0x{scope_id:016x}, binding: capnp_schema::ScopeBinding::Bind(vec![{bindings}]) }}")
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!("capnp_schema::Brand {{ scopes: vec![{scopes}] }}")
}

fn emit_struct(
    output: &mut String,
    schema: &CompiledSchema,
    node: &Node,
    structure: &capnp_schema::StructSchema,
    names: &Names,
) -> Result<(), GenerateError> {
    let module = names.get(node.id)?;
    let unrecognized = unique_variant(structure.fields.iter().map(|field| field.name.as_str()));
    let parameters = generic_parameters(schema, node);
    let declaration = generic_declaration(&parameters, true);
    let implementation = generic_declaration(&parameters, false);
    let arguments = generic_arguments(&parameters);
    let marker = marker_type(&parameters);
    let brand = generated_brand_expression(&parameters);
    let generated_bounds = parameters
        .iter()
        .map(|parameter| format!("{}: GeneratedType", parameter.name))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(output).map_err(|_| GenerateError::Format)?;
    emit_docs(output, schema, node, "Generated struct module")?;
    writeln!(output, "pub mod {module} {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    use super::*;").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub const TYPE_ID: u64 = 0x{:016x};", node.id)
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    #[derive(Clone, Debug)]").map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    pub struct Reader{declaration} {{ inner: capnp_schema::GeneratedStructReader, marker: PhantomData<fn() -> {marker}> }}"
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    impl{implementation} capnp_schema::FromDynamicStruct for Reader{arguments} {{"
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        const TYPE_ID: u64 = TYPE_ID;").map_err(|_| GenerateError::Format)?;
    writeln!(output, "        fn from_dynamic(value: capnp_schema::DynamicStruct) -> Result<Self, capnp_schema::DynamicError> {{ Ok(Self {{ inner: capnp_schema::GeneratedStructReader::new(value), marker: PhantomData }}) }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    impl{implementation} Reader{arguments} {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        pub fn from_root(schema: Arc<capnp_schema::CompiledSchema>, message: Arc<capnp_message::OwnedMessage>) -> Result<Self, capnp_schema::DynamicError>")
        .map_err(|_| GenerateError::Format)?;
    if generated_bounds.is_empty() {
        writeln!(output, "        {{").map_err(|_| GenerateError::Format)?;
    } else {
        writeln!(output, "        where {generated_bounds}\n        {{")
            .map_err(|_| GenerateError::Format)?;
    }
    if generated_bounds.is_empty() {
        writeln!(output, "            Ok(Self::from_dynamic_struct(capnp_schema::DynamicStruct::root(schema, message, TYPE_ID)?))")
            .map_err(|_| GenerateError::Format)?;
    } else {
        writeln!(output, "            Ok(Self::from_dynamic_struct(capnp_schema::DynamicStruct::root_branded(schema, message, TYPE_ID, {brand})?))")
            .map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "        #[doc(hidden)]\n        pub fn from_dynamic_struct(value: capnp_schema::DynamicStruct) -> Self {{ Self {{ inner: capnp_schema::GeneratedStructReader::new(value), marker: PhantomData }} }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "        pub fn dynamic(&self) -> &capnp_schema::DynamicStruct {{ self.inner.dynamic() }}"
    )
    .map_err(|_| GenerateError::Format)?;

    for (index, field) in structure.fields.iter().enumerate() {
        emit_field_docs(output, schema, node.id, index, field)?;
        emit_reader_field(output, schema, field, names, &parameters)?;
    }
    if structure.discriminant_count > 0 {
        writeln!(
            output,
            "        pub fn which(&self) -> Result<Which, capnp_schema::DynamicError> {{"
        )
        .map_err(|_| GenerateError::Format)?;
        writeln!(
            output,
            "            match self.inner.union_discriminant()?.unwrap_or(u16::MAX) {{"
        )
        .map_err(|_| GenerateError::Format)?;
        for field in &structure.fields {
            if let Some(discriminant) = field.discriminant_value {
                writeln!(
                    output,
                    "                {discriminant} => Ok(Which::{}),",
                    rust_pascal(&field.name)
                )
                .map_err(|_| GenerateError::Format)?;
            }
        }
        writeln!(
            output,
            "                value => Ok(Which::{unrecognized}(value)),"
        )
        .map_err(|_| GenerateError::Format)?;
        writeln!(output, "            }}").map_err(|_| GenerateError::Format)?;
        writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    impl{implementation} ListElement for Reader{arguments} {{"
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        fn from_dynamic(value: capnp_schema::DynamicValue) -> Result<Self, capnp_schema::DynamicError> {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "            match value {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "                capnp_schema::DynamicValue::Struct(Some(value)) if value.type_id() == TYPE_ID => Ok(Self::from_dynamic_struct(value)),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "                _ => Err(capnp_schema::DynamicError::TypeMismatch {{ expected: \"matching struct list element\" }}),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "            }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;

    writeln!(
        output,
        "    impl{implementation} GeneratedType for Reader{arguments}"
    )
    .map_err(|_| GenerateError::Format)?;
    if generated_bounds.is_empty() {
        writeln!(output, "    {{").map_err(|_| GenerateError::Format)?;
    } else {
        writeln!(output, "    where {generated_bounds} {{").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "        fn schema_type() -> capnp_schema::Type {{ capnp_schema::Type::Struct {{ type_id: TYPE_ID, brand: {brand} }} }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;

    let rpc_bounds = parameters
        .iter()
        .map(|parameter| format!("{}: GeneratedType + Send + 'static", parameter.name))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(
        output,
        "    impl{implementation} capnp_rpc::TypedReader for Reader{arguments}"
    )
    .map_err(|_| GenerateError::Format)?;
    if rpc_bounds.is_empty() {
        writeln!(output, "    {{").map_err(|_| GenerateError::Format)?;
    } else {
        writeln!(output, "    where {rpc_bounds} {{").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "        fn from_message(schema: Arc<capnp_schema::CompiledSchema>, message: Arc<capnp_message::OwnedMessage>) -> Result<Self, capnp_rpc::RpcError> {{ Self::from_root(schema, message).map_err(Into::into) }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;

    writeln!(output, "    #[derive(Clone, Debug)]").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub struct Pipeline{declaration} {{ transform: capnp_rpc::PipelineTransform, source: Option<capnp_rpc::PipelineSource>, marker: PhantomData<fn() -> {marker}> }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    impl{implementation} Pipeline{arguments} {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        pub fn root() -> Self {{ Self::from_transform(capnp_rpc::PipelineTransform::root()) }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        #[doc(hidden)]\n        pub fn from_transform(transform: capnp_rpc::PipelineTransform) -> Self {{ Self::from_parts(transform, None) }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        #[doc(hidden)]\n        pub fn from_parts(transform: capnp_rpc::PipelineTransform, source: Option<capnp_rpc::PipelineSource>) -> Self {{ Self {{ transform, source, marker: PhantomData }} }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "        pub fn transform(&self) -> &capnp_rpc::PipelineTransform {{ &self.transform }}"
    )
    .map_err(|_| GenerateError::Format)?;
    for field in &structure.fields {
        emit_pipeline_field(output, schema, field, names, &parameters)?;
    }
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    impl{implementation} capnp_rpc::PipelineBinding for Pipeline{arguments}"
    )
    .map_err(|_| GenerateError::Format)?;
    if rpc_bounds.is_empty() {
        writeln!(output, "    {{").map_err(|_| GenerateError::Format)?;
    } else {
        writeln!(output, "    where {rpc_bounds} {{").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "        fn bind(mut self, source: capnp_rpc::PipelineSource) -> Self {{ self.source = Some(source); self }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;

    writeln!(output, "    #[allow(dead_code)]").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub struct Builder<'schema, 'arena{comma}{params}> {{ inner: capnp_schema::DynamicStructBuilder<'schema, 'arena>, marker: PhantomData<fn() -> {marker}> }}",
        comma = if parameters.is_empty() { "" } else { ", " },
        params = parameters.iter().map(|parameter| format!("{} = capnp_schema::DynamicValue", parameter.name)).collect::<Vec<_>>().join(", "))
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    #[allow(dead_code)]").map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    impl<'schema, 'arena{comma}{params}> Builder<'schema, 'arena{comma}{args}> {{",
        comma = if parameters.is_empty() { "" } else { ", " },
        params = parameters
            .iter()
            .map(|parameter| parameter.name.as_str())
            .collect::<Vec<_>>()
            .join(", "),
        args = parameters
            .iter()
            .map(|parameter| parameter.name.as_str())
            .collect::<Vec<_>>()
            .join(", ")
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        pub fn init_root(schema: &'schema capnp_schema::CompiledSchema, arena: &'arena mut capnp_message::ExclusiveArena) -> Result<Self, capnp_schema::DynamicError>")
        .map_err(|_| GenerateError::Format)?;
    if generated_bounds.is_empty() {
        writeln!(output, "        {{").map_err(|_| GenerateError::Format)?;
    } else {
        writeln!(output, "        where {generated_bounds}\n        {{")
            .map_err(|_| GenerateError::Format)?;
    }
    if generated_bounds.is_empty() {
        writeln!(output, "            Ok(Self {{ inner: capnp_schema::DynamicStructBuilder::root(schema, arena, TYPE_ID)?, marker: PhantomData }})")
            .map_err(|_| GenerateError::Format)?;
    } else {
        writeln!(output, "            Ok(Self {{ inner: capnp_schema::DynamicStructBuilder::root_branded(schema, arena, TYPE_ID, {brand})?, marker: PhantomData }})")
            .map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "        }}").map_err(|_| GenerateError::Format)?;
    writeln!(output, "        #[doc(hidden)]\n        pub fn from_dynamic(inner: capnp_schema::DynamicStructBuilder<'schema, 'arena>) -> Self {{ Self {{ inner, marker: PhantomData }} }}")
        .map_err(|_| GenerateError::Format)?;
    for field in &structure.fields {
        emit_builder_field(output, schema, field, names, &parameters)?;
    }
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;

    if structure.discriminant_count > 0 {
        writeln!(
            output,
            "    #[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]"
        )
        .map_err(|_| GenerateError::Format)?;
        writeln!(output, "    pub enum Which {{").map_err(|_| GenerateError::Format)?;
        for field in &structure.fields {
            if field.discriminant_value.is_some() {
                writeln!(output, "        {},", rust_pascal(&field.name))
                    .map_err(|_| GenerateError::Format)?;
            }
        }
        writeln!(output, "        {unrecognized}(u16),").map_err(|_| GenerateError::Format)?;
        writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "}}").map_err(|_| GenerateError::Format)?;
    Ok(())
}

const STREAM_RESULT_TYPE_ID: NodeId = 0x995f_9a33_77c0_b16e;

fn method_parameters(
    base: &[GenericParameter],
    method: &capnp_schema::Method,
) -> Vec<GenericParameter> {
    let mut output = base.to_vec();
    let mut used = output
        .iter()
        .map(|parameter| parameter.name.clone())
        .collect::<BTreeSet<_>>();
    for (index, parameter) in method.implicit_parameters.iter().enumerate() {
        let base_name = rust_pascal(&parameter.name);
        let mut name = base_name.clone();
        let mut suffix = 2usize;
        while !used.insert(name.clone()) {
            name = format!("{base_name}{suffix}");
            suffix += 1;
        }
        if let Ok(index) = u16::try_from(index) {
            output.push(GenericParameter {
                scope_id: IMPLICIT_METHOD_SCOPE,
                index,
                name,
            });
        }
    }
    output
}

fn method_generic_declaration(base_len: usize, context: &[GenericParameter]) -> String {
    let method = &context[base_len..];
    if method.is_empty() {
        String::new()
    } else {
        format!(
            "<{}>",
            method
                .iter()
                .map(|parameter| format!("{}: GeneratedType + Send + 'static", parameter.name))
                .collect::<Vec<_>>()
                .join(", ")
        )
    }
}

fn interface_server_type(
    schema: &CompiledSchema,
    type_id: NodeId,
    brand: Option<&Brand>,
    names: &Names,
    context: &[GenericParameter],
) -> Result<String, GenerateError> {
    let arguments = branded_arguments(schema, type_id, brand, names, context)?;
    let suffix = if arguments.is_empty() {
        String::new()
    } else {
        format!("<{}>", arguments.join(", "))
    };
    Ok(format!(
        "{}::Server{suffix}",
        names.reference(type_id, true)?
    ))
}

fn method_struct_type(
    schema: &CompiledSchema,
    type_id: NodeId,
    brand: &Brand,
    names: &Names,
    context: &[GenericParameter],
    method: &capnp_schema::Method,
    member: &str,
) -> Result<String, GenerateError> {
    let target = schema
        .node(type_id)
        .ok_or(GenerateError::UnknownType(type_id))?;
    let target_parameters = generic_parameters(schema, target);
    let mut arguments = branded_arguments(schema, type_id, Some(brand), names, context)?;
    for (target_parameter, argument) in target_parameters.iter().zip(&mut arguments) {
        if argument != "capnp_schema::DynamicValue" {
            continue;
        }
        if let Some((index, _)) = method
            .implicit_parameters
            .iter()
            .enumerate()
            .find(|(_, parameter)| rust_pascal(&parameter.name) == target_parameter.name)
        {
            if let Ok(index) = u16::try_from(index) {
                if let Some(name) = parameter_name(context, IMPLICIT_METHOD_SCOPE, index) {
                    *argument = name.to_owned();
                }
            }
        }
    }
    let suffix = if arguments.is_empty() {
        String::new()
    } else {
        format!("<{}>", arguments.join(", "))
    };
    Ok(format!(
        "{}::{member}{suffix}",
        names.reference(type_id, true)?
    ))
}

fn emit_interface(
    output: &mut String,
    schema: &CompiledSchema,
    node: &Node,
    interface: &capnp_schema::InterfaceSchema,
    names: &Names,
) -> Result<(), GenerateError> {
    let module = names.get(node.id)?;
    let parameters = generic_parameters(schema, node);
    let declaration = generic_declaration(&parameters, true);
    let implementation = generic_declaration(&parameters, false);
    let arguments = generic_arguments(&parameters);
    let marker = marker_type(&parameters);
    let type_bounds = parameters
        .iter()
        .map(|parameter| format!("{}: GeneratedType + Send + Sync + 'static", parameter.name))
        .collect::<Vec<_>>()
        .join(", ");

    writeln!(output).map_err(|_| GenerateError::Format)?;
    emit_docs(output, schema, node, "Generated RPC interface module")?;
    writeln!(output, "pub mod {module} {{").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    use super::*;").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub const TYPE_ID: u64 = 0x{:016x};", node.id)
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    #[derive(Clone, Debug)]").map_err(|_| GenerateError::Format)?;
    writeln!(output, "    pub struct Client{declaration} {{ inner: capnp_rpc::LocalClient, marker: PhantomData<fn() -> {marker}> }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    impl{implementation} Client{arguments}")
        .map_err(|_| GenerateError::Format)?;
    let client_bounds = parameters
        .iter()
        .map(|parameter| format!("{}: GeneratedType + Send + 'static", parameter.name))
        .collect::<Vec<_>>()
        .join(", ");
    if client_bounds.is_empty() {
        writeln!(output, "    {{").map_err(|_| GenerateError::Format)?;
    } else {
        writeln!(output, "    where {client_bounds} {{").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "        pub fn from_local(inner: capnp_rpc::LocalClient) -> Self {{ Self {{ inner, marker: PhantomData }} }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "        pub fn local(&self) -> &capnp_rpc::LocalClient {{ &self.inner }}"
    )
    .map_err(|_| GenerateError::Format)?;
    for method in &interface.methods {
        let context = method_parameters(&parameters, method);
        let method_generics = method_generic_declaration(parameters.len(), &context);
        let method_name = rust_snake(&method.name);
        let params = method_struct_type(
            schema,
            method.param_struct_type,
            &method.param_brand,
            names,
            &context,
            method,
            "Reader",
        )?;
        if method.result_struct_type == STREAM_RESULT_TYPE_ID {
            writeln!(output, "        pub fn {method_name}{method_generics}(&self, params: impl Into<capnp_rpc::LocalRequest>) -> capnp_rpc::StreamingCall {{ self.inner.call_streaming_request(TYPE_ID, {}, params.into()) }}", method.code_order)
                .map_err(|_| GenerateError::Format)?;
        } else {
            let results = method_struct_type(
                schema,
                method.result_struct_type,
                &method.result_brand,
                names,
                &context,
                method,
                "Reader",
            )?;
            let pipeline = method_struct_type(
                schema,
                method.result_struct_type,
                &method.result_brand,
                names,
                &context,
                method,
                "Pipeline",
            )?;
            let pipeline_expression = expression_path(&pipeline);
            writeln!(output, "        pub fn {method_name}{method_generics}(&self, params: impl Into<capnp_rpc::LocalRequest>) -> capnp_rpc::PendingCall<{results}, {pipeline}> {{ self.inner.call_request(TYPE_ID, {}, params.into(), {pipeline_expression}::root()) }}", method.code_order)
                .map_err(|_| GenerateError::Format)?;
        }
        let _ = params;
    }
    for superclass in &interface.superclasses {
        let super_node = schema
            .node(superclass.id)
            .ok_or(GenerateError::UnknownType(superclass.id))?;
        let method_name = format!(
            "as_{}",
            rust_snake(super_node.short_name().unwrap_or(&super_node.display_name))
        );
        let target = interface_client_type(
            schema,
            superclass.id,
            Some(&superclass.brand),
            names,
            &parameters,
        )?;
        writeln!(output, "        pub fn {method_name}(&self) -> {target} {{ {target}::from_local(self.inner.clone()) }}")
            .map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    impl{implementation} capnp_rpc::FromLocalClient for Client{arguments}"
    )
    .map_err(|_| GenerateError::Format)?;
    if client_bounds.is_empty() {
        writeln!(output, "    {{").map_err(|_| GenerateError::Format)?;
    } else {
        writeln!(output, "    where {client_bounds} {{").map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "        fn from_local_client(client: capnp_rpc::LocalClient) -> Self {{ Self::from_local(client) }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;

    let supertraits = interface
        .superclasses
        .iter()
        .map(|superclass| {
            interface_server_type(
                schema,
                superclass.id,
                Some(&superclass.brand),
                names,
                &parameters,
            )
        })
        .collect::<Result<Vec<_>, _>>()?;
    let inheritance = if supertraits.is_empty() {
        String::new()
    } else {
        format!("{} + ", supertraits.join(" + "))
    };
    writeln!(
        output,
        "    pub trait Server{declaration}: {inheritance}Send + Sync + 'static {{"
    )
    .map_err(|_| GenerateError::Format)?;
    for method in &interface.methods {
        let context = method_parameters(&parameters, method);
        let method_generics = method_generic_declaration(parameters.len(), &context);
        let method_name = rust_snake(&method.name);
        let params = method_struct_type(
            schema,
            method.param_struct_type,
            &method.param_brand,
            names,
            &context,
            method,
            "Reader",
        )?;
        writeln!(output, "        fn {method_name}{method_generics}(&self, _params: {params}) -> capnp_rpc::MessageFuture {{ Box::pin(async {{ Err(capnp_rpc::RpcError::Unimplemented {{ interface_id: TYPE_ID, method_id: {} }}) }}) }}", method.code_order)
            .map_err(|_| GenerateError::Format)?;
    }
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;

    writeln!(output, "    pub struct LocalServer<S{comma}{params}> {{ server: Arc<S>, schema: Arc<capnp_schema::CompiledSchema>, marker: PhantomData<fn() -> {marker}> }}",
        comma = if parameters.is_empty() { "" } else { ", " },
        params = parameters.iter().map(|parameter| format!("{} = capnp_schema::DynamicValue", parameter.name)).collect::<Vec<_>>().join(", "))
        .map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    impl<S{comma}{params}> LocalServer<S{comma}{args}> {{",
        comma = if parameters.is_empty() { "" } else { ", " },
        params = parameters
            .iter()
            .map(|parameter| parameter.name.as_str())
            .collect::<Vec<_>>()
            .join(", "),
        args = parameters
            .iter()
            .map(|parameter| parameter.name.as_str())
            .collect::<Vec<_>>()
            .join(", ")
    )
    .map_err(|_| GenerateError::Format)?;
    writeln!(output, "        pub fn new(server: Arc<S>, schema: Arc<capnp_schema::CompiledSchema>) -> Self {{ Self {{ server, schema, marker: PhantomData }} }}")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "    }}").map_err(|_| GenerateError::Format)?;
    writeln!(
        output,
        "    impl<S{comma}{params}> capnp_rpc::LocalService for LocalServer<S{comma}{args}>",
        comma = if parameters.is_empty() { "" } else { ", " },
        params = parameters
            .iter()
            .map(|parameter| parameter.name.as_str())
            .collect::<Vec<_>>()
            .join(", "),
        args = parameters
            .iter()
            .map(|parameter| parameter.name.as_str())
            .collect::<Vec<_>>()
            .join(", ")
    )
    .map_err(|_| GenerateError::Format)?;
    let mut bounds = vec![format!("S: Server{arguments}")];
    if !type_bounds.is_empty() {
        bounds.push(type_bounds);
    }
    writeln!(output, "    where {} {{", bounds.join(", ")).map_err(|_| GenerateError::Format)?;
    writeln!(output, "        fn dispatch(self: Arc<Self>, interface_id: u64, method_id: u16, params: Arc<capnp_message::OwnedMessage>) -> capnp_rpc::MessageFuture {{")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "            match (interface_id, method_id) {{")
        .map_err(|_| GenerateError::Format)?;
    emit_dispatch_arms(
        output,
        schema,
        node.id,
        interface,
        names,
        &parameters,
        "Server",
    )?;
    for superclass in &interface.superclasses {
        let super_node = schema
            .node(superclass.id)
            .ok_or(GenerateError::UnknownType(superclass.id))?;
        let NodeKind::Interface(super_interface) = &super_node.kind else {
            return Err(GenerateError::UnknownType(superclass.id));
        };
        let server_type = interface_server_type(
            schema,
            superclass.id,
            Some(&superclass.brand),
            names,
            &parameters,
        )?;
        emit_dispatch_arms(
            output,
            schema,
            superclass.id,
            super_interface,
            names,
            &parameters,
            &server_type,
        )?;
    }
    writeln!(output, "                (TYPE_ID, method_id) => Box::pin(async move {{ Err(capnp_rpc::RpcError::UnknownMethod {{ interface_id: TYPE_ID, method_id }}) }}),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "                (interface_id, _) => Box::pin(async move {{ Err(capnp_rpc::RpcError::UnknownInterface(interface_id)) }}),")
        .map_err(|_| GenerateError::Format)?;
    writeln!(output, "            }}\n        }}\n    }}\n}}")
        .map_err(|_| GenerateError::Format)?;
    Ok(())
}

fn emit_dispatch_arms(
    output: &mut String,
    schema: &CompiledSchema,
    interface_id: NodeId,
    interface: &capnp_schema::InterfaceSchema,
    names: &Names,
    parameters: &[GenericParameter],
    server_trait: &str,
) -> Result<(), GenerateError> {
    for method in &interface.methods {
        let mut context = method_parameters(parameters, method);
        for parameter in &mut context[parameters.len()..] {
            parameter.name = "capnp_schema::DynamicValue".to_owned();
        }
        let params_type = method_struct_type(
            schema,
            method.param_struct_type,
            &method.param_brand,
            names,
            &context,
            method,
            "Reader",
        )?;
        let method_name = rust_snake(&method.name);
        let turbofish = if method.implicit_parameters.is_empty() {
            String::new()
        } else {
            format!(
                "::<{}>",
                method
                    .implicit_parameters
                    .iter()
                    .map(|_| "capnp_schema::DynamicValue")
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        };
        writeln!(
            output,
            "                (0x{interface_id:016x}, {}) => {{",
            method.code_order
        )
        .map_err(|_| GenerateError::Format)?;
        writeln!(output, "                    let reader = match <{params_type} as capnp_rpc::TypedReader>::from_message(Arc::clone(&self.schema), params) {{ Ok(value) => value, Err(error) => return Box::pin(async move {{ Err(error) }}), }};")
            .map_err(|_| GenerateError::Format)?;
        writeln!(
            output,
            "                    {server_trait}::{method_name}{turbofish}(&*self.server, reader)"
        )
        .map_err(|_| GenerateError::Format)?;
        writeln!(output, "                }},").map_err(|_| GenerateError::Format)?;
    }
    Ok(())
}

